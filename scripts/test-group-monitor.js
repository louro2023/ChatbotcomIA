const assert = require('assert/strict');
const { createGroupMonitor } = require('../Electron/group-monitor');
(async () => {
  let state = {}, account = 'one@c.us';
  const sent = [];
  const options = { read: () => structuredClone(state), write: next => { state = structuredClone(next); }, account: () => account, send: async (...args) => { sent.push(args); } };
  const monitor = createGroupMonitor(options);
  const groupId = '1@g.us';
  const update = payload => monitor.update({ groupId, ...payload });
  update({ action: 'save-command', trigger: '!AJUDA', response: 'Olá 👋\nhttps://example.com', enabled: true });
  assert.throws(() => update({ action: 'save-command', trigger: '!ajuda', response: 'duplicado' }), /já existe/);
  assert.throws(() => update({ action: 'save-command', trigger: 'ajuda', response: 'x' }), /iniciado/);
  assert.throws(() => update({ action: 'save-command', trigger: '!com espaço', response: 'x' }), /sem espaços/);
  const msg = (body, id = body, extra = {}) => ({ from: groupId, body, id: { _serialized: id }, ...extra });
  assert.equal(await monitor.handle(msg('!ajuda')), false);
  update({ action: 'toggle-group', enabled: true });
  assert.equal(await monitor.handle(msg('olá !ajuda')), false);
  assert.equal(await monitor.handle(msg('!ajuda extra')), false);
  assert.equal(await monitor.handle(msg('!ajuda', 'own', { fromMe: true })), false);
  assert.equal(await monitor.handle(msg('!ajuda', 'other', { from: '2@g.us' })), false);
  await Promise.all([monitor.handle(msg(' !AJUDA ', 'same')), monitor.handle(msg(' !AJUDA ', 'same'))]);
  assert.equal(sent.length, 1);
  assert.equal(await monitor.handle(msg('!ajuda', 'same')), false);
  const command = monitor.settings()[groupId].commands[0];
  update({ action: 'toggle-command', id: command.id, enabled: false });
  assert.equal(await monitor.handle(msg('!ajuda', 'disabled')), false);
  update({ action: 'save-command', id: command.id, trigger: '!novo', response: 'nova', enabled: true });
  assert.equal(await monitor.handle(msg('!ajuda', 'old')), false);
  await monitor.handle(msg('!novo', 'new'));
  assert.equal(sent.at(-1)[1], 'nova');
  account = 'two@c.us';
  assert.deepEqual(monitor.settings(), {});
  assert.equal(await monitor.handle(msg('!novo', 'account')), false);
  account = 'one@c.us';
  assert.equal(createGroupMonitor(options).settings()[groupId].commands[0].trigger, '!novo');
  update({ action: 'delete-command', id: command.id });
  assert.equal(monitor.settings()[groupId].commands.length, 0);
  monitor.update({ groupId: '2@g.us', action: 'toggle-group', enabled: true });
  assert.equal(monitor.settings()[groupId].enabled, false);
  assert.equal(monitor.settings()['2@g.us'].enabled, true);
  assert.equal(Object.values(monitor.settings()).filter(group => group.enabled).length, 1);
  account = '';
  assert.equal(await monitor.handle(msg('!novo')), false);
  console.log('Monitoramento de grupos: validações, ativação, isolamento, persistência e deduplicação OK.');
})().catch(error => { console.error(error); process.exitCode = 1; });
